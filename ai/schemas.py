from typing import List, Literal, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator

# Restricted Action Schema for MVP
SupportedActionType = Literal["delete_users"]
SupportedActionCondition = Literal[
    "inactive_90_days",
    "created_90_days",
    "inactive_or_unknown"
]

class Action(BaseModel):
    """Restricted action schema executable by the simulator."""
    type: SupportedActionType = Field(
        ...,
        description="Permitted action type (must be 'delete_users' for MVP)."
    )
    condition: SupportedActionCondition = Field(
        ...,
        description="Permitted filtering condition ('inactive_90_days', 'created_90_days', 'inactive_or_unknown')."
    )

class CandidateInterpretation(BaseModel):
    """Interpretation candidate generated by the AI engine before simulation."""
    id: Literal["A", "B", "C"] = Field(..., description="Branch identifier: 'A', 'B', or 'C'")
    title: str = Field(..., min_length=1, description="Concise title for the interpretation")
    assumption: str = Field(..., min_length=5, description="The unstated operational assumption")
    action: Action = Field(..., description="The restricted simulated action to execute")
    explanation: str = Field(..., min_length=5, description="Why this interpretation was derived")
    risk_level: Optional[Literal["low", "medium", "high", "critical"]] = Field(
        default="medium",
        description="Estimated operational risk level"
    )

class CandidateAmbiguity(BaseModel):
    """An ambiguous term detected in the instruction."""
    term: str = Field(..., min_length=1, description="The ambiguous word or phrase (e.g., 'old')")
    description: str = Field(..., min_length=5, description="Why the term is ambiguous")
    interpretation_ids: List[str] = Field(..., description="Relevant interpretation IDs, e.g. ['A', 'B']")
    impact: str = Field(..., min_length=5, description="Real-world consequence of the divergence")

class AIEngineOutput(BaseModel):
    """Structured output from the AI engine matching the contract."""
    interpretations: List[CandidateInterpretation] = Field(
        ...,
        min_length=3,
        max_length=3,
        description="Exactly three plausible interpretations"
    )
    candidate_ambiguities: List[CandidateAmbiguity] = Field(
        ...,
        min_length=1,
        description="Identified ambiguous terms, descriptions, and relevant IDs"
    )
    suggested_rewrite: str = Field(
        ...,
        min_length=10,
        description="Clearer, unambiguous version of the instruction"
    )

    @field_validator("interpretations")
    @classmethod
    def validate_unique_branches(cls, v: List[CandidateInterpretation]) -> List[CandidateInterpretation]:
        ids = [i.id for i in v]
        if set(ids) != {"A", "B", "C"}:
            raise ValueError(f"Interpretations must have IDs 'A', 'B', and 'C', got: {ids}")
        return v
